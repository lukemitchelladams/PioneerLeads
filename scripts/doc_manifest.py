#!/usr/bin/env python3
"""Document-package check for every bid folder (CLAUDE.md rule 0c).

For each bids/<bid>/docs/ it reads the extracted text of every solicitation file (*.txt, or extracts PDFs
with pdftotext), finds every referenced Attachment / Exhibit / Appendix / Addendum / Form / Price Sheet /
Template, and checks whether a matching file is present in docs/. Writes bids/<bid>/docs/MANIFEST.md and
prints a summary. Usage:
    python3 scripts/doc_manifest.py                 # all bids
    python3 scripts/doc_manifest.py littleton       # bids whose folder name contains "littleton"
"""
from __future__ import annotations

import re
import subprocess
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parents[1]
BIDS = REPO / "bids"
REF_RX = re.compile(
    r"\b(Attachment|Exhibit|Appendix|Addendum|Schedule|Form)\s+(?:No\.?\s*)?([A-Z]{1,2}\d?|\d{1,2}(?:\.\d)?)\b"
    r"(?:\s*[-:–—]\s*([A-Z][A-Za-z0-9 ,/&()'\-]{3,70}))?")
TEMPLATE_RX = re.compile(r"(pric\w+ (sheet|form|template|schedule|workbook)|bid (form|schedule|tab)|template provided)", re.I)
SKIP_NAMES = {"MANIFEST.md"}


def texts(docs: Path) -> dict[str, str]:
    out = {}
    for f in sorted(docs.iterdir()):
        if f.suffix.lower() == ".txt":
            out[f.name] = f.read_text(errors="ignore")
        elif f.suffix.lower() == ".pdf" and not (docs / (f.stem + ".txt")).exists() \
                and not (docs / (f.stem + ".extracted.txt")).exists():
            try:
                out[f.name] = subprocess.run(["pdftotext", "-layout", str(f), "-"], capture_output=True,
                                             text=True, timeout=120).stdout
            except Exception:  # noqa: BLE001
                pass
    return out


def norm(s: str) -> str:
    return re.sub(r"[^a-z0-9]+", "", s.lower())


def present(files: list[str], kind: str, label: str, title: str | None) -> str | None:
    keys = [norm(f"{kind}{label}"), norm(f"{kind[:3]}{label}")]
    if title:
        keys.append(norm(title)[:18])
    for f in files:
        nf = norm(f)
        if any(k and k in nf for k in keys):
            return f
    return None


def inside(text: str, kind: str, label: str) -> bool:
    """True when the item appears as a heading in the body (not just the table of contents):
    a line that starts with e.g. 'EXHIBIT A' / 'Attachment 2' after the first 8% of the document,
    with no page-number tail (TOC lines end in a page number)."""
    lines = text.splitlines()
    if re.search(r"all (attachments|exhibits|appendices)[^.]{0,40}(uploaded|provided|posted|attached) separately", text, re.I):
        return False
    start = max(1, int(len(lines) * 0.20))
    rx = re.compile(rf"^\s*{kind}\s+(?:No\.?\s*)?{re.escape(label)}\b(?!.*\.{{3,}})(?!.*\s\d{{1,3}}\s*$)", re.I)
    return any(rx.search(ln) for ln in lines[start:])


SEPARATE_RX = re.compile(r"uploaded separately|separate (file|attachment)|attached separately|provided separately|in RMEPS|in BidNet", re.I)


def manifest(bid: Path) -> tuple[int, int, list[str]]:
    docs = bid / "docs"
    if not docs.is_dir():
        return 0, 0, []
    files = [f.name for f in docs.iterdir() if f.is_file() and f.name not in SKIP_NAMES]
    refs: dict[str, dict] = {}
    template_hits = []
    alltext = texts(docs)
    for src, t in alltext.items():
        flat = re.sub(r"[ \t]+", " ", t)
        for m in REF_RX.finditer(flat):
            kind, label, title = m.group(1).title(), m.group(2).upper(), (m.group(3) or "").strip()
            k = f"{kind} {label}"
            if k not in refs or (title and not refs[k]["title"]):
                refs[k] = {"kind": kind, "label": label, "title": title, "source": src}
        for m in TEMPLATE_RX.finditer(flat):
            template_hits.append(flat[max(0, m.start() - 60): m.end() + 60].replace("\n", " ").strip())
    rows, missing = [], []
    for k, r in sorted(refs.items()):
        hit = present(files, r["kind"], r["label"], r["title"])
        near_sep = bool(SEPARATE_RX.search(r["title"] or "")) or any(
            SEPARATE_RX.search(t[max(0, i - 200): i + 300])
            for t in alltext.values() for i in [m.start() for m in re.finditer(rf"{r['kind']}\s+{re.escape(r['label'])}\b", t, re.I)])
        in_doc = None if (hit or near_sep) else next((src for src, t in alltext.items() if inside(t, r["kind"], r["label"])), None)
        if hit:
            status = "IN HAND: " + hit
        elif in_doc:
            status = f"INSIDE {in_doc} (heading found; verify pages)"
        else:
            status = "**MISSING**"
        rows.append(f"| {k} | {r['title']} | {r['source']} | {status} |")
        if not hit and not in_doc:
            missing.append(f"{k} {r['title']}".strip())
    lines = [f"# Document package: {bid.name}", "",
             "Generated by scripts/doc_manifest.py (CLAUDE.md rule 0c). Every attachment/exhibit/appendix/form the",
             "solicitation references, and whether we hold it. Send ALL in-hand files; name every MISSING one + where to get it.", "",
             "## Files in docs/", ""] + [f"- {f}" for f in sorted(files)] + ["",
             "## Referenced in the solicitation", "", "| Item | Title | Referenced in | Status |", "|---|---|---|---|"] + rows
    if template_hits:
        lines += ["", "## Pricing forms / templates mentioned (check each is in hand)", ""]
        lines += [f"- ...{h}..." for h in dict.fromkeys(template_hits)][:10]
    (docs / "MANIFEST.md").write_text("\n".join(lines) + "\n")
    return len(refs), len(missing), missing


def main() -> int:
    flt = sys.argv[1].lower() if len(sys.argv) > 1 else ""
    for bid in sorted(p for p in BIDS.iterdir() if p.is_dir() and not p.name.startswith("_")):
        if flt and flt not in bid.name:
            continue
        n, miss, names = manifest(bid)
        if n or miss:
            print(f"{bid.name}: {n} referenced, {miss} missing" + (": " + "; ".join(names) if names else ""))
    return 0


if __name__ == "__main__":
    sys.exit(main())
